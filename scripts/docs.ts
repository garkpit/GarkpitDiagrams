// Writes the README's command reference from cli/commands.ts (the table `diagrams help` prints from),
// and the rule list from src/check.ts. With --check, fails if the README is out of date.
//   bun scripts/docs.ts          rewrite the README section
//   bun scripts/docs.ts --check  exit 1 when it has drifted (part of `bun run check`)
import { COMMANDS, GLOBAL_FLAGS, INPUT_HELP } from '../cli/commands.ts';
import { RULES } from '../src/check.ts';

const readme = `${import.meta.dir}/../README.md`;
const flag = (f: { name: string; short?: string; value?: string }) => `\`${f.short ? `-${f.short}, ` : ''}--${f.name}${f.value ? ` ${f.value}` : ''}\``;
const parts: string[] = ['<!-- cli:start (generated by `bun run docs` from cli/commands.ts; do not edit) -->', '', INPUT_HELP, ''];
for (const c of COMMANDS) {
  parts.push(`### \`diagrams ${c.name}${c.args ? ` ${c.args}` : ''}\``, '', `${c.summary} ${c.detail}`, '');
  if (c.flags.length) {
    parts.push('| Flag | What it does |', '|---|---|');
    for (const f of c.flags) parts.push(`| ${flag(f)} | ${f.desc} |`);
    parts.push('');
  }
  parts.push('```sh', ...c.examples, '```', '');
}
parts.push('Global flags: ' + GLOBAL_FLAGS.map((f) => `${flag(f)} ${f.desc.toLowerCase().replace(/\.$/, '')}`).join('; ') + '.', '');
parts.push('### Fit-check rules', '', '| Rule | Severity | Catches |', '|---|---|---|');
for (const r of RULES) parts.push(`| \`${r.rule}\` | ${r.severity} | ${r.what} |`);
parts.push('', '<!-- cli:end -->');
const section = parts.join('\n');

const text = await Bun.file(readme).text();
const re = /<!-- cli:start[\s\S]*?<!-- cli:end -->/;
if (!re.test(text)) {
  console.error('README.md has no <!-- cli:start --> … <!-- cli:end --> markers');
  process.exit(1);
}
const next = text.replace(re, section);
if (process.argv.includes('--check')) {
  if (next !== text) {
    console.error('README.md command reference is out of date. Fix: bun run docs');
    process.exit(1);
  }
  console.log('README.md command reference is current');
} else {
  await Bun.write(readme, next);
  console.log('wrote the command reference into README.md');
}
